"""Downloads Material Symbols Rounded (Apache 2.0) and writes them as vector drawables.

Usage: scripts/fetch-icons.py   (edit ICONS below, then run again)
"name" gives res/drawable/ic_name.xml; "name+" also gives ic_name_fill.xml (filled style).
"""
