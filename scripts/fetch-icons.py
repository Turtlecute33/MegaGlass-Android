ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "app/src/main/res/drawable")
URL = "https://raw.githubusercontent.com/google/material-design-icons/master/symbols/web/{n}/materialsymbolsrounded/{n}{v}_24px.svg"

TEMPLATE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Material Symbols Rounded "{name}", Apache License 2.0, generated by scripts/fetch-icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:autoMirrored="{mirror}"
    android:tint="?android:attr/colorControlNormal"
    android:viewportWidth="960"
    android:viewportHeight="960">
    <group android:translateY="960">
        <path android:fillColor="@android:color/white" android:pathData="{path}" />
    </group>
</vector>
"""
MIRRORED = {"arrow_back", "arrow_forward", "chevron_right", "chevron_left", "logout", "send", "open_in_new", "drive_file_move"}

def fetch(job):
    name, fill = job
    url = URL.format(n=name, v="_fill1" if fill else "")
    try:
        svg = urllib.request.urlopen(url, timeout=30).read().decode()
    except Exception as e:
        return f"FAILED {name}{' fill' if fill else ''}: {e}"
    paths = re.findall(r'<path d="([^"]+)"', svg)
    out = TEMPLATE.format(name=name, path=" ".join(paths), mirror=str(name in MIRRORED).lower())
    fname = f"ic_{name}{'_fill' if fill else ''}.xml"
    with open(os.path.join(OUT, fname), "w") as f:
        f.write(out)
    return None

jobs = []
for icon in ICONS:
    name = icon.rstrip("+")
    jobs.append((name, False))
    if icon.endswith("+"):
        jobs.append((name, True))

with concurrent.futures.ThreadPoolExecutor(16) as ex:
    errors = [e for e in ex.map(fetch, jobs) if e]
print(f"{len(jobs) - len(errors)} icons written")
for e in errors:
    print(e, file=sys.stderr)
